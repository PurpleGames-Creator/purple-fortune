const TEMPER_SPARK = [1, 0, 3, 2]; // 刺激をくれる気質

function goodAttrs(attr) {
  return [(attr + 4) % 12, (attr + 8) % 12, (attr + 6) % 12];
}
function sparkAttr(attr) {
  return (attr + 3) % 12;
}

